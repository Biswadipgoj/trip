import { useCallback } from 'react'
import { useStore } from './store'

/** Get a translated string for a key, falling back to English. */
export function getTranslation(lang: string, key: TranslationKey): string {
  const current = DICTIONARY[lang]
  if (current && current[key]) return current[key]!
  return DICTIONARY.en?.[key] || key
}

export function useTranslation() {
  const language = useStore(s => s.language) || 'en'
  const setLanguage = useStore(s => s.setLanguage)
  const t = useCallback((key: TranslationKey) => getTranslation(language, key), [language])
  return { t, language, setLanguage, languages: LANGUAGES }
}

